"""Приведение всех видов тире к обычному дефису-минусу «-»."""

HYPHEN_MINUS = "-"

# Все символы Unicode-категории Pd (dash punctuation), кроме самого «-»,
# плюс знак минуса и маркер-дефис, которые визуально тоже являются тире.
DASH_CHARS: frozenset[str] = frozenset(
    {
        "֊",  # армянский дефис
        "־",  # еврейский макаф
        "᐀",  # канадский слоговой дефис
        "᠆",  # монгольский дефис
        "‐",  # ‐ дефис
        "‑",  # ‑ неразрывный дефис
        "‒",  # ‒ цифровое тире
        "–",  # – короткое тире
        "—",  # — длинное тире
        "―",  # ― горизонтальная черта
        "⁃",  # ⁃ маркер-дефис
        "−",  # − знак минуса
        "⸗",  # двойной косой дефис
        "⸚",  # дефис с диерезисом
        "⸺",  # ⸺ двойное тире
        "⸻",  # ⸻ тройное тире
        "⹀",  # двойной дефис
        "⹝",  # косой дефис
        "〜",  # волнистое тире
        "〰",  # волнистая черта
        "゠",  # двойной дефис катаканы
        "︱",  # вертикальное длинное тире
        "︲",  # вертикальное короткое тире
        "﹘",  # ﹘ малое длинное тире
        "﹣",  # ﹣ малый дефис-минус
        "－",  # － полноширинный дефис-минус
        "\U00010D6E",  # дефис гарай
        "\U00010EAD",  # езидский дефис
    }
)

_TABLE = str.maketrans({ch: HYPHEN_MINUS for ch in DASH_CHARS})


def normalize_dashes(text: str) -> str:
    return text.translate(_TABLE)


def contains_dashes(text: str) -> bool:
    return any(ch in DASH_CHARS for ch in text)
