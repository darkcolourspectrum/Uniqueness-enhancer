def build_sample(path: Path) -> Path:
    d = docx.Document()
    d.styles["Normal"].font.size = Pt(14)

    section = d.sections[0]
    section.header.paragraphs[0].text = "Блог о здоровье — выпуск 12"
    section.footer.paragraphs[0].text = "© 2026 – все права защищены"

    d.add_heading(TITLE, level=1)
    for heading, paragraphs in SECTIONS:
        if heading:
            d.add_heading(heading, level=2)
        for text in paragraphs:
            d.add_paragraph(text)

    for item in BULLETS:
        d.add_paragraph(item, style="List Bullet")

    d.add_heading("Примерный план на первый месяц", level=2)
    table = d.add_table(rows=len(TABLE), cols=3)
    table.style = "Table Grid"
    for r, row in enumerate(TABLE):
        for c, value in enumerate(row):
            table.cell(r, c).text = value
    d.add_paragraph()

    for heading, paragraphs in TAIL:
        d.add_heading(heading, level=2)
        for text in paragraphs:
            if text is None:
                p = d.add_paragraph("Полезно вести дневник тренировок: записывайте дистанцию, "
                                    "время и самочувствие. ")
                p.add_run("Видимый прогресс").bold = True
                p.add_run(" — лучшая мотивация, особенно в первые недели.")
            else:
                d.add_paragraph(text)

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    d.save(str(path))
    return path


if __name__ == "__main__":
    default = Path(__file__).resolve().parent.parent / "samples" / "sample_article.docx"
    print(build_sample(Path(sys.argv[1]) if len(sys.argv) > 1 else default))
